package com.FreeRave.remindme.screens.ai

import android.util.Log
import androidx.compose.runtime.mutableStateListOf
import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import com.FreeRave.remindme.model.Reminder
import com.FreeRave.remindme.service.FirebaseAuthServiceInterface
import com.FreeRave.remindme.service.GeminiService
import com.FreeRave.remindme.service.ReminderService
import com.google.gson.Gson
import com.google.gson.JsonObject
import dagger.hilt.android.lifecycle.HiltViewModel
import kotlinx.coroutines.flow.MutableSharedFlow
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asSharedFlow
import kotlinx.coroutines.launch
import java.util.UUID
import javax.inject.Inject

sealed class AiActionEffect {
    data class NavigateToEditReminder(val reminderId: String) : AiActionEffect()
    data class NavigateToAddReminder(
        val title: String?,
        val reminderTime: Long?,
        val isRecurring: Boolean?,
        val recurrenceIntervalMillis: Long?,
        val recurrenceEndTime: Long?
    ) : AiActionEffect()
    data class ShowToast(val message: String) : AiActionEffect()
}

@HiltViewModel
class AiViewModel @Inject constructor(
    private val geminiService: GeminiService,
    private val reminderService: ReminderService,
    private val firebaseAuthService: FirebaseAuthServiceInterface
) : ViewModel() {

    private val _actionEffect = MutableSharedFlow<AiActionEffect>()
    val actionEffect = _actionEffect.asSharedFlow()

    private val _chatMessages = mutableStateListOf<ChatMessage>()
    val chatMessages: List<ChatMessage> = _chatMessages

    private val _userInput = MutableStateFlow("")
    val userInput: StateFlow<String> = _userInput

    private val _isLoading = MutableStateFlow(false)
    val isLoading: StateFlow<Boolean> = _isLoading

    init {
        _chatMessages.add(
            ChatMessage(
                text = "Hello! I'm your AI assistant. How can I help you manage your reminders today?",
                sender = SenderType.AI
            )
        )
    }

    fun onUserInputChange(text: String) {
        _userInput.value = text
    }

    fun sendMessage() {
        val userMessageText = _userInput.value.trim()
        if (userMessageText.isBlank()) return

        _chatMessages.add(ChatMessage(text = userMessageText, sender = SenderType.USER))
        _userInput.value = ""

        viewModelScope.launch {
            _isLoading.value = true

            try {
                val aiResponseText = geminiService.generateContent(userMessageText)

                if (aiResponseText.contains("ACTION_PARSE_REMINDER:")) {
                    try {
                        val jsonString = geminiService.parseReminderToJSON(userMessageText)

                        if (!jsonString.isNullOrBlank()) {
                            // clean the JSON string
                            val cleanJson = jsonString
                                .replace("```json", "")
                                .replace("```", "")
                                .trim()

                            val json = Gson().fromJson(cleanJson, JsonObject::class.java)

                            val title = if (json.has("title")) json.get("title").asString else ""
                            val reminderTime = if (json.has("reminderTime") && !json.get("reminderTime").isJsonNull)
                                json.get("reminderTime").asLong else null
                            val isRecurring = if (json.has("isRecurring")) json.get("isRecurring").asBoolean else false
                            val category = if (json.has("category")) json.get("category").asString else "Other"

                            if (title.isNotBlank() && reminderTime != null) {
                                val currentUserId = firebaseAuthService.getCurrentUserId()

                                if (currentUserId.isBlank()) {
                                    _chatMessages.add(
                                        ChatMessage(
                                            text = "I understood: $title. Please log in to save reminders.",
                                            sender = SenderType.AI
                                        )
                                    )
                                } else {
                                    val newReminder = Reminder(
                                        id = UUID.randomUUID().toString(),
                                        customId = "",
                                        title = title,
                                        description = "Generated by AI",
                                        category = category,
                                        time = System.currentTimeMillis(),
                                        reminderTime = reminderTime,
                                        isRecurring = isRecurring,
                                        userId = currentUserId
                                    )

                                    reminderService.addReminder(newReminder)
                                    _chatMessages.add(
                                        ChatMessage(
                                            text = "Done! Reminder '$title' added ✅",
                                            sender = SenderType.AI
                                        )
                                    )
                                    _actionEffect.emit(AiActionEffect.ShowToast("Reminder Added!"))
                                }
                            } else {
                                // if data is missing, ask the user to try again
                                _chatMessages.add(
                                    ChatMessage(
                                        text = aiResponseText.replace("ACTION_PARSE_REMINDER: ", ""),
                                        sender = SenderType.AI
                                    )
                                )
                            }
                        }
                    } catch (e: Exception) {
                        Log.e("AiViewModel", "JSON Parse Error: ${e.message}")
                        _chatMessages.add(
                            ChatMessage(
                                text = "I understood the reminder, but had trouble saving the details. Can you try again?",
                                sender = SenderType.AI
                            )
                        )
                    }
                } else {
                    // دردشة عادية
                    _chatMessages.add(ChatMessage(text = aiResponseText, sender = SenderType.AI))
                }

            } catch (e: Exception) {
                Log.e("AiViewModel", "Gemini Error: ${e.message}")
                _chatMessages.add(
                    ChatMessage(
                        text = "Sorry, my brain is offline. Check your internet connection!",
                        sender = SenderType.AI
                    )
                )
            } finally {
                _isLoading.value = false
            }
        }
    }
}